package cz.vutbr.fit.interlockSim.testutil

import cz.vutbr.fit.interlockSim.ports.DispatchLoopSnapshot
import cz.vutbr.fit.interlockSim.ports.HighLevelCommandSource
import cz.vutbr.fit.interlockSim.sim.DispatchDecision

/**
 * The CI stand-in for the LLM dispatcher (Issue #1479, Goal 9B SP5.6): a [HighLevelCommandSource]
 * that writes high-level commands per control tick from a script.
 *
 * `ollama-test` tests are skipped in CI and Koog has no sampling seed, so no LLM run is repeatable.
 * A scripted run is: it is called once per control tick with that tick's observation and uses no
 * sleep, no wall clock and no random value. The three [Mode]s:
 *
 * - [fixedList]: a fixed command list per tick stamp;
 * - [ruleDriven]: a callback that reads the tick's observation (for the SP6 "perfect dispatcher"
 *   and the SP7 knot fixture);
 * - [silent]: never a command (for the R7 tests).
 *
 * Train names come from a process-wide counter, so a script addresses trains by generation
 * ordinal ([GeneratedTrains]), never by name.
 *
 * The planner names no author. The feeder writes author `LLM` for its commands and records the
 * run-level command source as scripted with [name] (ruling Q2 of #1474; the `:dispatcher-agent`
 * test adapter does both). Not thread-safe: it is called only on the simulation thread.
 *
 * @property name The script name, recorded as the run's command-source name.
 * @property mode Which of the three modes this planner runs.
 * @since Issue #1479 (Goal 9B SP5.6)
 */
class ScriptedPlanner private constructor(
	val name: String,
	val mode: Mode,
	private val script: (DispatchLoopSnapshot, GeneratedTrains) -> List<DispatchDecision>
) : HighLevelCommandSource {
	init {
		require(name.isNotBlank()) { "A script needs a name: it is the run's command-source name" }
	}

	/** The three modes of Issue #1479. */
	enum class Mode {
		/** A fixed command list per tick stamp. */
		FIXED_LIST,

		/** A callback that reads the observation of the tick. */
		RULE_DRIVEN,

		/** No command on any tick. */
		SILENT
	}

	/** The trains this planner has seen, numbered in generation order. */
	val generatedTrains: GeneratedTrains = GeneratedTrains()

	private val ticks = mutableListOf<Long>()

	/** The tick stamps of the observations this planner was called with, in call order. */
	val calledTicks: List<Long> get() = ticks.toList()

	override fun commandsAt(observation: DispatchLoopSnapshot): List<DispatchDecision> {
		generatedTrains.observe(observation)
		ticks += observation.tick
		return script(observation, generatedTrains)
	}

	companion object {
		/**
		 * The fixed-list mode: at each tick stamp of [commandsByTick] the planner writes that tick's
		 * commands, resolved against the trains generated so far; at every other tick it is silent.
		 * A command whose train has not been generated by its tick fails the run loudly.
		 */
		fun fixedList(
			name: String,
			commandsByTick: Map<Long, List<ScriptedCommand>>
		): ScriptedPlanner {
			require(commandsByTick.keys.all { it >= 1L }) {
				"Tick stamps start at 1 (the first control step); got ${commandsByTick.keys.sorted()}"
			}
			return ScriptedPlanner(name, Mode.FIXED_LIST) { observation, trains ->
				commandsByTick[observation.tick].orEmpty().map { it.resolve(trains) }
			}
		}

		/** The rule-driven mode: [rule] gets each tick's observation and the trains generated so far. */
		fun ruleDriven(
			name: String,
			rule: (observation: DispatchLoopSnapshot, trains: GeneratedTrains) -> List<DispatchDecision>
		): ScriptedPlanner = ScriptedPlanner(name, Mode.RULE_DRIVEN, rule)

		/** The silent mode: no command on any tick; every call is a silent cycle. */
		fun silent(name: String): ScriptedPlanner = ScriptedPlanner(name, Mode.SILENT) { _, _ -> emptyList() }
	}
}

/**
 * A fixed-list command that names its train by generation ordinal (1 = the first generated train
 * of the run), resolved to the train's name when the planner writes it.
 *
 * @since Issue #1479 (Goal 9B SP5.6)
 */
sealed interface ScriptedCommand {
	/** The generation ordinal of the train, 1-based. */
	val ordinal: Int

	/** The command for the train [trains] numbers [ordinal]. */
	fun resolve(trains: GeneratedTrains): DispatchDecision

	/** Admits the train: [DispatchDecision.ApproveTrain]. */
	data class ApproveTrain(
		override val ordinal: Int
	) : ScriptedCommand {
		override fun resolve(trains: GeneratedTrains): DispatchDecision =
			DispatchDecision.ApproveTrain(trains.nameOf(ordinal))
	}

	/** Reserves the train's path from a semaphore to a target: [DispatchDecision.ReservePath]. */
	data class ReservePath(
		override val ordinal: Int,
		val fromSemaphoreName: String,
		val toTargetName: String
	) : ScriptedCommand {
		override fun resolve(trains: GeneratedTrains): DispatchDecision =
			DispatchDecision.ReservePath(trains.nameOf(ordinal), fromSemaphoreName, toTargetName)
	}

	/** Requests a route for the train: [DispatchDecision.RequestRoute]. */
	data class RequestRoute(
		override val ordinal: Int,
		val fromEndpointName: String,
		val toEndpointName: String
	) : ScriptedCommand {
		override fun resolve(trains: GeneratedTrains): DispatchDecision =
			DispatchDecision.RequestRoute(trains.nameOf(ordinal), fromEndpointName, toEndpointName)
	}
}

/**
 * The trains a [ScriptedPlanner] has seen, numbered by generation ordinal: the order in which they
 * first appear in the observed queue of trains waiting for admission. Every generated train waits
 * in that queue for at least one published tick before anything can admit it, and the queue keeps
 * generation order, so the ordinal is the generation order of the run.
 *
 * Train names come from a process-wide counter: a second run in the same process names its trains
 * differently, so fixtures and assertions use ordinals.
 *
 * @since Issue #1479 (Goal 9B SP5.6)
 */
class GeneratedTrains {
	private val ordinalsByName = LinkedHashMap<String, Int>()

	/** The names of the generated trains, in generation order. */
	val names: List<String> get() = ordinalsByName.keys.toList()

	/** How many trains have been generated so far. */
	val count: Int get() = ordinalsByName.size

	/** Numbers every train of [observation]'s queue that has not been seen before. */
	fun observe(observation: DispatchLoopSnapshot) {
		observation.queuedTrains.forEach { ordinalsByName.getOrPut(it.trainId) { ordinalsByName.size + 1 } }
	}

	/** The name of the train generated as number [ordinal] (1-based). */
	fun nameOf(ordinal: Int): String {
		require(ordinal >= 1) { "Generation ordinals start at 1; got $ordinal" }
		return checkNotNull(ordinalsByName.entries.firstOrNull { it.value == ordinal }?.key) {
			"Train number $ordinal has not been generated yet; $count train(s) seen so far"
		}
	}

	/** The generation ordinal of the train named [name], or `null` for a train not seen. */
	fun ordinalOf(name: String): Int? = ordinalsByName[name]
}
